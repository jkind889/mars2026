create policy "Users can read their own profile"
on public.profiles
for select
to authenticated
using (user_id = auth.uid());

create policy "Users can update their own profile"
on public.profiles
for update
to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

create policy "Active posters are publicly readable"
on public.posters
for select
using (status = 'active');

create policy "Admins can manage posters"
on public.posters
for all
to authenticated
using (public.is_store_admin())
with check (public.is_store_admin());

create policy "Active variants for active posters are publicly readable"
on public.variants
for select
using (
  is_active
  and exists (
    select 1
    from public.posters
    where posters.id = variants.poster_id
      and posters.status = 'active'
  )
);

create policy "Admins can manage variants"
on public.variants
for all
to authenticated
using (public.is_store_admin())
with check (public.is_store_admin());

create policy "Admins can read admin users"
on public.admin_users
for select
to authenticated
using (public.is_store_admin());

create policy "Users can read their own admin user row"
on public.admin_users
for select
to authenticated
using (user_id = auth.uid());

create policy "Admins can manage admin users"
on public.admin_users
for all
to authenticated
using (public.is_store_admin())
with check (public.is_store_admin());

create policy "Users can read their own customer profile"
