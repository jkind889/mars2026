create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table public.instruments (
  id bigint generated by default as identity primary key,
  name text
);

create table public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz,
  email text,
  display_name varchar,
  stripe_customer_id text unique,
  role text
);

create table public.posters (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  description text,
  collection text,
  image_url text,
  status text not null default 'draft',
  sort_order integer,
  created_at timestamptz default now(),
  updated_at timestamptz
);

create table public.variants (
  id bigint generated by default as identity primary key,
  poster_id bigint not null references public.posters(id) on delete cascade,
  sku text,
  width_in smallint,
  height_in smallint,
  paper_type text,
  price_cents integer not null,
  currency text not null default 'usd',
  stripe_price_id text unique,
  is_active boolean not null default true,
  production_notes text,
  created_at timestamptz default now(),
  updated_at timestamptz,
  label text
);

create table public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table public.customer_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  stripe_customer_id text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id bigint generated by default as identity primary key,
  order_number text not null unique,
  user_id uuid references auth.users(id) on delete set null,
  stripe_customer_id text,
  stripe_checkout_session_id text unique,
  stripe_payment_intent_id text,
  payment_status text,
  fulfillment_status text,
  subtotal_cents integer,
  shipping_cents integer,
  tax_cents integer,
  total_cents integer,
  currency text,
  customer_email text,
  shipping_name text,
  shipping_address_line1 text,
  shipping_address_line2 text,
  shipping_city text,
  shipping_state text,
  shipping_postal_code text,
  shipping_country text,
  tracking_number text,
  paid_at timestamptz,
  shipped_at timestamptz,
  created_at timestamptz default now(),
  updated_at timestamptz
);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  variant_id bigint references public.variants(id) on delete set null,
  poster_id bigint references public.posters(id) on delete set null,
  quantity integer,
  unit_price_cents integer,
  line_total_cents integer,
  poster_title_snapshot text,
  variant_label_snapshot text,
  poster_image_snapshot text,
  created_at timestamptz default now()
);

create index posters_active_created_at_idx
  on public.posters(created_at desc)
  where status = 'active';

create index posters_slug_status_idx
  on public.posters(slug, status);

create index variants_poster_active_price_idx
  on public.variants(poster_id, is_active, price_cents);

create index orders_user_created_at_idx
  on public.orders(user_id, created_at desc);

create index orders_stripe_customer_id_idx
  on public.orders(stripe_customer_id)
  where stripe_customer_id is not null;

create index orders_created_at_idx
  on public.orders(created_at desc);

create index orders_payment_status_idx
  on public.orders(payment_status);

create index orders_fulfillment_status_idx
  on public.orders(fulfillment_status);

create index order_items_order_id_idx
  on public.order_items(order_id);

create index order_items_poster_id_idx
  on public.order_items(poster_id);

create index order_items_variant_id_idx
  on public.order_items(variant_id);

